// Hand-pixelled hair for the game's own hero portraits ("Portraits: Game"): the 24x24 portrait, the 32x32 win and
// lose faces and the 16x16 HUD heads of Alex (the boy) and Nina (the girl), one drawing per hairstyle. The face is the
// game's (eyes, mouth, expression stay pixel for pixel, taken from the ROM at run time); only the hair, and the hat or
// band a style needs, is drawn here, as rows of region letters. The regions take the look's colours (label.js REG), so
// every skin and hair colour works. Pixel art written for this project; nothing here is copied from the ROM.
//
// Legend (one character per pixel; a row may be shorter than the frame: the rest is left as is):
//   ' '  leave as it is (the template's pixel)       '.'  card (portraits) / transparent (heads)
//   '='  the game's own pixel, as labelled            '!'  the game's pixel, a dark pixel labelled hair becomes outline
//   '~'  the game's pixel, hair-coloured bits of it become skin shade (hands)
//   '#'  outline   'H' hair   'D' hair, dark   'L' hair, light   's' skin   'd' skin shade   'h' skin highlight
//   'T'  hat / band   't' top   'k' white (the game's colour)
// A template per hero and frame clears the game's hair, hat and buns and keeps the face: each style is drawn over it.
