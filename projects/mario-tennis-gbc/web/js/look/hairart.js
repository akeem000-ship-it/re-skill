// ---------------------------------------------------------------------------------------------- apply
function stamp(st, y0, rows, mode) {
  const { w, h, reg, idx, lay } = st, ring = st.kind === "portrait";
  rows.forEach((row, k) => {
    const y = y0 + k; if (y < (ring ? 1 : 0) || y >= h - (ring ? 1 : 0)) return;
    for (let x = ring ? 1 : 0; x < w - (ring ? 1 : 0) && x < row.length; x++) {
      const c = row[x], i = y * w + x; if (c === " " || c === "=") continue;
      if (c === "!") { if (isHair(reg[i]) && idx[i] === 3) reg[i] = OUT; continue; }
      if (c === "~") { if (isHair(reg[i])) { reg[i] = SHADE; idx[i] = lay[SHADE]; } continue; }
      let r = CH[c]; if (r === undefined) throw new Error("hairart: unknown pixel '" + c + "'");
      if (r === CARD && !ring) r = NONE;
      reg[i] = r; idx[i] = r === NONE ? 0 : r === CARD ? 0 : r === KEEP ? 1 : lay[r];
    }
  });
}

// frame: "portrait" | "win" | "lose" | "head"
export const hasHairArt = (hero, style, frame) => !!(ART[hero] && ART[hero][style] && ART[hero][style][frame]);
export function applyHairArt(st, hero, style, frame) {
  const art = ART[hero] && ART[hero][style] && ART[hero][style][frame]; if (!art) return false;
  const T = FACE[hero][frame];
  stamp(st, T.y, T.rows);
  stamp(st, art.y, art.rows);
  return true;
}
// the bald template alone (tests and the art tools)
export function applyFaceTemplate(st, hero, frame) { const T = FACE[hero][frame]; stamp(st, T.y, T.rows); return st; }
