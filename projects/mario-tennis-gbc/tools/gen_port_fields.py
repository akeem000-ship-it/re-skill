"""Generate web/js/port/fields.js: every named RAM variable of the game (WRAM0, WRAMX banks 1-7, HRAM) from the
vendored disassembly's symbol file, as [name, bank, address, size]. Names drop the w/h prefix and lower the first
letter (wCurMapID -> curMapID), like the match engine's fields; the size is the distance to the next symbol
(capped, so a buffer's name addresses its first byte).

usage: python3 tools/gen_port_fields.py [path/to/mariotennis.sym]
(build the symbol file first: third_party/mario-tennis-gbc-disasm, ./setup.sh ROM && make)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYM = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "third_party/mario-tennis-gbc-disasm/build/mariotennis.sym")
OUT = os.path.join(ROOT, "web/js/port/fields.js")

syms = []
for line in open(SYM):
    m = re.match(r"([0-9a-f]{2}):([0-9a-f]{4}) ([wh][A-Z]\w*)$", line.strip())
    if not m:
        continue
    bank, addr, name = int(m.group(1), 16), int(m.group(2), 16), m.group(3)
    if not (0xC000 <= addr < 0xE000 or 0xFF80 <= addr <= 0xFFFE):
        continue
    if addr < 0xD000 or addr >= 0xFF80:
        bank = 0
    syms.append((bank, addr, name))
syms.sort(key=lambda s: (s[0], s[1], s[2]))
rows, seen = [], set()
for i, (bank, addr, name) in enumerate(syms):
    nxt = next((a for b, a, _ in syms[i + 1:] if b == bank and a > addr), None)
    end = 0x10000 if addr >= 0xFF80 else (0xD000 if addr < 0xD000 else 0xE000)
    size = min((nxt or end) - addr, 0x1000)
    js = name[1].lower() + name[2:]
    if js in seen:
        js = f"{js}_{bank}"
    seen.add(js)
    rows.append(f'  ["{js}", {bank}, 0x{addr:04X}, {size}],')
with open(OUT, "w") as f:
    f.write("// GENERATED by tools/gen_port_fields.py from the gerbiljames/mario-tennis-gbc-disasm symbols (MIT,\n")
    f.write("// third_party/mario-tennis-gbc-disasm). [name, WRAM bank (0 = WRAM0/HRAM), address, size in bytes].\n")
    f.write("export const RAM_FIELDS = [\n" + "\n".join(rows) + "\n];\n")
print(f"{len(rows)} fields -> {OUT}")
